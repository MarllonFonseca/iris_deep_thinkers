  function exacta(c) {
    if (Object.prototype.hasOwnProperty.call(MAPA, c)) return MAPA[c];
    for (var i = 0; i < REGRAS.length; i++) {
      var m = c.match(REGRAS[i][0]);
      if (m) return typeof REGRAS[i][1] === "function" ? REGRAS[i][1].apply(null, m.concat([trad])) : c.replace(REGRAS[i][0], REGRAS[i][1]);
    }
    return null;
  }
  // uma frase: exacta, ou por partes " · "
  function frase(c) {
    var r = exacta(c);
    if (r !== null) return r;
    if (c.indexOf(" · ") !== -1) {
      var alguma = false;
      var o = c.split(" · ").map(function (p) {
        var x = exacta(p);
        if (x === null && /\.$/.test(p)) { x = exacta(p.slice(0, -1)); if (x !== null) x = x.replace(/\.?$/, "."); }
        if (x !== null) { alguma = true; return x; } return p;
      });
      if (alguma) return o.join(" · ");
    }
    return null;
  }
  function trad(s) {
    if (s === null || s === undefined) return s;
    s = String(s);
    var m = s.match(/^(\s*)([\s\S]*?)(\s*)$/), c = dia0(m[2]);
    if (!c) return s;
    if (lingua() !== "pt") return m[1] + c + m[3];
    var r = exacta(c);
    if (r === null && /[.?!] [A-Z“"]/.test(c)) {
      // várias frases: cada uma (exacta ou por partes)
      var fr = c.replace(/([.?!]) (?=[A-Z“"])/g, "$1\u0001").split("\u0001"), algum = false;
      var rr = fr.map(function (p) {
        var x = frase(p);
        if (x === null && /\.$/.test(p)) { x = frase(p.slice(0, -1)); if (x !== null) x = x.replace(/\.?$/, "."); }
        if (x !== null) { algum = true; return x; } return p;
      }).join(" ");
      if (algum) r = rr;
    }
    if (r === null) r = frase(c);
    return m[1] + (r === null ? c : r) + m[3];
  }

